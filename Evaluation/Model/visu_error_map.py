# System (Default)
import sys
#   Add access if it is not in the system path.
if '../../' + 'src' not in sys.path:
    sys.path.append('../../' + 'src')
# Numpy (Array computing) [pip3 install numpy]
import numpy as np
# OS (Operating system interfaces)
import os
# SciencePlots (Matplotlib styles for scientific plotting) [pip3 install SciencePlots]
import scienceplots
# Matplotlib (Visualization) [pip3 install matplotlib]
import matplotlib.pyplot as plt
import matplotlib.colors
# Custom Lib.:
#   ../Parameters/Robot
import Parameters.Robot
#   ../Kinematics/Core
import Kinematics.Core
#   ../FCNN_IK/Model
import FCNN_IK.Model
#   ../Utilities/Dataset
import Utilities.Dataset as Dataset

"""
Description:
    Initialization of constants.
"""
# Set the structure of the main parameters of the robot.
CONST_ROBOT_TYPE = Parameters.Robot.EPSON_LS3_B401S_Str
# The models (dataset configurations) to be visualized.
CONST_NUM_OF_DATA = [1000, 10000, 100000]
# The name of the fixed test set (without extension).
#   Note:
#       The test set is generated by ../Dataset_Generation/generate.py (seed 1),
#       e.g. $ python generate.py 10000 test
CONST_TEST_SET_NAME = 'Test_N_10000'
# Save the figure to the file (*.png) for the README.
#   Note:
#       f'{project_folder}/images/Error_Map.png'
CONST_SAVE_FIGURE = False

def main():
    """
    Description:
        The program to visualize the absolute position error of the neural-network predictor over the workspace.

        Each point of the fixed test set (both configurations of the solution) is drawn at its desired position (x, y)
        and colored by the position error ||p - FK(theta_predicted)|| in millimeters. All models share the same
        logarithmic color scale.
    """

    # Locate the path to the project folder.
    project_folder = os.getcwd().split('FCNN_Inverse_Kinematics')[0] + 'FCNN_Inverse_Kinematics'

    # Initialization of the structure of the main parameters of the robot.
    Robot_Str = CONST_ROBOT_TYPE

    # Read the fixed test set from a file (*.zip).
    data = Dataset.Load(f'{project_folder}/Data/Dataset/{CONST_TEST_SET_NAME}').values
    p = data[:, 0:2]

    e_p = []; num_of_data = []
    for _, N_i in enumerate(CONST_NUM_OF_DATA):
        file_path = f'{project_folder}/Data/Model/Config_N_{N_i}'
        if not os.path.isfile(f'{file_path}.keras'):
            print(f'[WARNING] The model {file_path}.keras does not exist. The model is skipped.')
            continue

        # Prediction of the absolute joint position of the robotic arm.
        #   1\ Initialization.
        FCNN_IK_Predictor_Cls = FCNN_IK.Model.FCNN_Predictor_Cls(f'{file_path}_Scaler_x.pkl', f'{file_path}_Scaler_y.pkl',
                                                                 f'{file_path}.keras', Robot_Str)
        #   2\ Prediction (batch).
        (_, theta_predicted) = FCNN_IK_Predictor_Cls.Predict(data[:, 0:3], verbose=False)

        # Obtain the absolute position error in millimeters.
        e_p_i = 1000.0 * np.linalg.norm(p - Kinematics.Core.Forward_Kinematics(theta_predicted, Robot_Str)[1], axis=1)
        e_p.append(e_p_i); num_of_data.append(N_i)
        print(f'[INFO] N = {N_i}: e_p mean = {np.mean(e_p_i):.4g} mm, max = {np.max(e_p_i):.4g} mm')

        # Release class object.
        del FCNN_IK_Predictor_Cls

    if e_p == []:
        print('[ERROR] No model was found.')
        return 1

    # Set the parameters for the scientific style.
    plt.style.use('science')

    # Shared logarithmic color scale of all models.
    norm = matplotlib.colors.LogNorm(vmin=np.min([np.min(e_p_i[e_p_i > 0.0]) for e_p_i in e_p]),
                                     vmax=np.max([np.max(e_p_i) for e_p_i in e_p]))

    # Create a figure.
    figure, ax = plt.subplots(1, len(e_p), figsize=(5.0 * len(e_p), 4.6), squeeze=False, constrained_layout=True)
    ax = ax[0]

    for i, (e_p_i, N_i) in enumerate(zip(e_p, num_of_data)):
        # Visualization of the test points colored by the position error (the largest errors on top).
        idx = np.argsort(e_p_i)
        scatter = ax[i].scatter(p[idx, 0], p[idx, 1], c=np.maximum(e_p_i[idx], norm.vmin), s=2.0, cmap='viridis',
                                norm=norm, linewidths=0.0, rasterized=True)

        # Set parameters of the graph (plot).
        ax[i].set_title(f'N = {N_i}: mean $e_p$ = {np.mean(e_p_i):.3g} mm', fontsize=12, pad=8.0)
        #   Label.
        ax[i].set_xlabel(r'x-axis in meters', fontsize=11, labelpad=6)
        if i == 0:
            ax[i].set_ylabel(r'y-axis in meters', fontsize=11, labelpad=6)
        #   Set parameters of the visualization.
        ax[i].set_aspect('equal')
        ax[i].grid(which='major', linewidth = 0.15, linestyle = '--')

    # Shared color bar.
    color_bar = figure.colorbar(scatter, ax=ax.tolist(), shrink=0.85, pad=0.02)
    color_bar.set_label(r'$e_{p}$ in millimeters (log scale)', fontsize=11, labelpad=8)

    figure.suptitle(f'Absolute Position Error over the Workspace (test set, {data.shape[0]} samples, both configurations)',
                    fontsize=13)

    # Save the figure.
    #   Note:
    #       dpi = 120 keeps the file below ~1 MB (10000 colored points per panel).
    if CONST_SAVE_FIGURE == True:
        figure.savefig(f'{project_folder}/images/Error_Map.png', dpi=120, bbox_inches='tight')
        print(f'[INFO] >> file_path = {project_folder}/images/Error_Map.png')

    # Show the result.
    plt.show()

if __name__ == "__main__":
    sys.exit(main())
